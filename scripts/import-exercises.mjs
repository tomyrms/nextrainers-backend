// Generates lib/exercise-library.ts from the repository-root content/exercises.json
// for every exercise that is not hand-curated in lib/seed.ts (EXERCISE_SOURCES).
//
// content/ has no block type nor rules, so they are derived:
//   - type: mental -> cooldown; short (<= 12 min) U6-U13 technique/athletic
//     games -> warmup; long (>= 20 min) collective tactical themes ->
//     gameApplication; everything else -> mainExercises.
//   - rules: the description's sentences (up to 3).
//
// Usage (from nextrainers-backend/): node scripts/import-exercises.mjs [path/to/content/exercises.json]
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const source = process.argv[2] ?? path.join("..", "content", "exercises.json");
const all = JSON.parse(readFileSync(source, "utf8"));
const seed = readFileSync(path.join("lib", "seed.ts"), "utf8");
const curated = new Set([...seed.matchAll(/^\s{4}id: "(ex_\d+)",$/gm)].map((m) => m[1]));

const GAME_THEMES = new Set([
  "jeu de position",
  "attaque placée",
  "conservation",
  "bloc équipe",
  "pressing",
  "sortie de balle",
  "transition",
  "coups de pied arrêtés",
]);

function typeFor(e) {
  if (e.theme === "mental") return "cooldown";
  const young = e.category === "U6-U9" || e.category === "U10-U13";
  if (young && e.durationMin <= 12 && (e.theme === "technique" || e.theme === "athletique")) return "warmup";
  if (e.durationMin >= 20 && e.theme === "tactique" && GAME_THEMES.has(e.subTheme)) return "gameApplication";
  return "mainExercises";
}

function rulesFor(description) {
  return description
    .split(/(?<=[.!?])\s+/)
    .map((s) => s.trim())
    .filter((s) => s.length > 0)
    .slice(0, 3);
}

const entries = all
  .filter((e) => !curated.has(e.id))
  .map((e) => ({
    id: e.id,
    title: e.name,
    type: typeFor(e),
    duration: e.durationMin,
    players: [e.playersMin, e.playersMax],
    equipment: e.equipment,
    subTheme: e.subTheme,
    description: e.description,
    coachingPoints: e.coachingPoints,
    variations: e.variations,
    rules: rulesFor(e.description),
  }));

const out = `// GENERATED by scripts/import-exercises.mjs from content/exercises.json — do not edit.
// The ${entries.length} library exercises that are not hand-curated in lib/seed.ts.
import type { ExerciseSource } from "./seed";

export const LIBRARY_EXERCISE_SOURCES: ExerciseSource[] = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync(path.join("lib", "exercise-library.ts"), out, "utf8");
console.log(`curated ${curated.size}, generated ${entries.length}:`, Object.entries(entries.reduce((acc, e) => ((acc[e.type] = (acc[e.type] ?? 0) + 1), acc), {})));
